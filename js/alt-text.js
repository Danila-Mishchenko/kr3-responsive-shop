  const priceFormat = new Intl.NumberFormat('ru-RU', {
    style: 'currency',
    currency: 'RUB',
    maximumFractionDigits: 0,
  });
 
  function findProduct(id) {
    const list = typeof instruments === 'undefined' ? [] : instruments;
    const product = list.find((item) => item.id === id);
    if (product) return product;
    const facts = productFacts[id];
    if (!facts) return null;
    return { title: facts[0], category: facts[1], specs: facts[2], description: facts[3] };
  }
 
  function priceSentence(product) {
    if (typeof product.price !== 'number') return '';
    const discount = product.discountPercent || 0;
    const final = product.price - Math.round(product.price * discount) / 100;
    const status = product.isAvailable === false ? 'Сейчас нет в наличии.' : 'В наличии.';
    const price = discount
      ? `Цена со скидкой ${discount}%: ${priceFormat.format(final)}, без скидки ${priceFormat.format(product.price)}.`
      : `Цена: ${priceFormat.format(final)}.`;
    return ` ${price} ${status}`;
  }
 
  function productAlt(id, short) {
    const look = productLook[id];
    const product = findProduct(id);
    if (!look || !product) return null;
    if (short) return `${product.title}. ${look}`;
    return (
      `${product.title}. ${look} ` +
      `Категория: ${product.category}. Характеристики: ${product.specs}. ` +
      `${product.description}${priceSentence(product)}`
    );
  }
 
  function altFor(image) {
    const source = image.getAttribute('src') || '';
    const match = source.match(/images\/([\w/-]+?)(?:-\d+)?\.webp/);
    if (!match) return null;
    const key = match[1];
    if (productLook[key]) return productAlt(key, Boolean(image.closest('.category-tile')));
    return photoAlt[key] || null;
  }
 
  function applyAlt(image) {
    // Декоративные миниатюры и значки скрыты от скринридера, их не трогаем.
    if (image.getAttribute('aria-hidden') === 'true') return;
    const text = altFor(image);
    if (text && image.getAttribute('alt') !== text) image.setAttribute('alt', text);
  }
 
  function applyAll() {
    for (const image of document.images) applyAlt(image);
  }
 
  let planned = false;
  function plan() {
    if (planned) return;
    planned = true;
    queueMicrotask(() => {
      planned = false;
      applyAll();
    });
  }
 
  applyAll();
  new MutationObserver(plan).observe(document.body, {
    childList: true,
    subtree: true,
    attributes: true,
    attributeFilter: ['src', 'alt'],
  });
